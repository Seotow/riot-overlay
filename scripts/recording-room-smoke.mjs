import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
import {mkdir} from 'node:fs/promises';
const base=process.env.OVERLAY_VISUAL_URL;
assert.match(base??'',/^http:\/\/127\.0\.0\.1:\d+$/);assert.ok(!base.endsWith(':4310'));
const {chromium}=createRequire(import.meta.url)(resolve(process.env.OVERLAY_BROWSER_PACKAGES,'playwright'));
const browser=await chromium.launch({channel:'msedge',headless:true});
const report=async()=>await(await fetch(base+'/api/providers')).json();
const until=async(check)=>{for(let i=0;i<120;i++){if(await check())return;await new Promise(r=>setTimeout(r,100));}throw Error('Condition timeout');};
try {
  const before=await report(),page=await browser.newPage({viewport:{width:1920,height:1080}}),errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.goto(base+'/?page=demo');
  await page.getByRole('button',{name:'Tải bản ghi',exact:true}).waitFor();
  await until(async()=>!!(await page.getByLabel('Bộ dữ liệu thật',{exact:true}).inputValue()));
  assert.equal((await report()).selected,before.selected,'Opening page must not change source');
  assert.equal(await page.locator('.real-test-panel,.scene-grid,.event-buttons').count(),0);
  const id=await page.getByLabel('Bộ dữ liệu thật',{exact:true}).inputValue();
  await page.getByRole('button',{name:'Tải bản ghi',exact:true}).click();
  await page.getByRole('button',{name:'Phát bản ghi',exact:true}).waitFor({timeout:60000});
  assert.equal(await page.locator('.operator-card').count(),6);
  assert.equal(await page.locator('.operator-card button:disabled').count(),0);
  const overlay=await browser.newPage({viewport:{width:1920,height:1080}});
  await overlay.goto(base+'/overlay?scene=ingame');
  await overlay.locator('.live-player-row .row-champion img').first().waitFor();
  const snapshot=await report();assert.equal(snapshot.recording.frames,1525);
  await page.getByRole('button',{name:'Phát bản ghi',exact:true}).click();
  await until(async()=> (await report()).recording.positionMs>1000);
  await page.getByRole('button',{name:'Tạm dừng bản ghi',exact:true}).click();
  await until(async()=> !(await report()).recording.playing);
  const paused=(await report()).recording.positionMs;
  await new Promise(r=>setTimeout(r,700));assert.equal((await report()).recording.positionMs,paused);
  const slider=page.getByRole('slider',{name:'Tiến độ bản ghi thật'});
  await slider.evaluate(e=>e.value='25000');await slider.dispatchEvent('pointerup');
  await until(async()=> (await report()).recording.positionMs===25000);
  const gameTime=(await report()).recording.gameTime;
  const clock=`${Math.floor(gameTime/60).toString().padStart(2,'0')}:${Math.floor(gameTime%60).toString().padStart(2,'0')}`;
  await until(async()=>await page.getByTestId('recorded-game-time').textContent()===clock);
  await until(async()=>await overlay.locator('.live-scoreboard .score-sub time').textContent()===clock);
  for(const title of ['Leaderboard vàng','Leaderboard cấp độ','Rune toàn đội','Layout tối giản']){
    const card=page.locator('.operator-card').filter({has:page.getByRole('heading',{name:title,exact:true})});
    await card.getByRole('button').click();
    await card.getByRole('button',{name:'Đang phát · tắt',exact:true}).waitFor();
    assert.equal((await report()).recording.positionMs,25000,'Widget must not jump to a rehearsed target');
  }
  await overlay.locator('.canvas.minimal').waitFor();
  await page.getByRole('button',{name:'Trở về bảng đầy đủ',exact:true}).click();
  await overlay.locator('.canvas.panel').waitFor();
  await page.getByRole('button',{name:'+10 giây',exact:true}).click();
  await until(async()=> (await report()).recording.positionMs===35000);
  await page.getByLabel('Tốc độ bản ghi',{exact:true}).selectOption('2');
  await until(async()=> (await report()).recording.speed===2);
  await slider.press('End');
  await until(async()=>{const r=(await report()).recording;return r.positionMs===r.durationMs;});
  await page.getByRole('button',{name:'Về đầu bản ghi',exact:true}).click();
  await until(async()=> (await report()).recording.positionMs===0);
  await mkdir('.npm-cache/visual-audit',{recursive:true});
  await page.screenshot({path:'.npm-cache/visual-audit/recording-room-current.png',fullPage:true});
  for(const width of [1920,1280]){await page.setViewportSize({width,height:1080});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));}
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({pass:true,capture:id,frames:snapshot.recording.frames,gameTime:clock,controlsIndependentOfMarkers:true,legacyUiHidden:true,playPauseSeekSpeed:true,obsMatches:true}));
} finally {await browser.close();}
