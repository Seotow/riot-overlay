import { readFile, writeFile, mkdir } from "node:fs/promises";
// Separate complete draft catalog; keep the approved demo catalog unchanged.
const version = "15.20.1",
  root = `public/ddragon/${version}`;
try {
  await readFile(`${root}/data/champion.json`);
} catch {
  const response = await fetch(
    `https://ddragon.leagueoflegends.com/cdn/${version}/data/en_US/champion.json`,
  );
  if (!response.ok) throw Error(`Metadata ${response.status}`);
  await mkdir(`${root}/data`, { recursive: true });
  await writeFile(
    `${root}/data/champion.json`,
    Buffer.from(await response.arrayBuffer()),
  );
}
const metadata = JSON.parse(
  await readFile(`${root}/data/champion.json`, "utf8"),
).data;
await mkdir(`${root}/loading`, { recursive: true });
await mkdir(`${root}/champion`, { recursive: true });
const entries = Object.values(metadata);
let cursor = 0;
await Promise.all(
  Array.from({ length: 6 }, async () => {
    while (cursor < entries.length) {
      const c = entries[cursor++];
      for (const [path, url] of [
        [
          `champion/${c.id}.png`,
          `https://ddragon.leagueoflegends.com/cdn/${version}/img/champion/${c.id}.png`,
        ],
        [
          `loading/${c.id}_0.jpg`,
          `https://ddragon.leagueoflegends.com/cdn/img/champion/loading/${c.id}_0.jpg`,
        ],
      ]) {
        try {
          await readFile(`${root}/${path}`);
        } catch {
          const response = await fetch(url);
          if (!response.ok) throw Error(`${response.status}: ${url}`);
          await writeFile(
            `${root}/${path}`,
            Buffer.from(await response.arrayBuffer()),
          );
        }
      }
    }
  }),
);
const champions = Object.fromEntries(
  entries.map((c) => [
    c.id,
    {
      id: c.id,
      key: c.key,
      name: c.name,
      icon: `/ddragon/${version}/champion/${c.id}.png`,
      portrait: `/ddragon/${version}/loading/${c.id}_0.jpg`,
    },
  ]),
);
// Preserve optional centered artwork generated by the separate art sync.
try {
  const previous = JSON.parse(
    await readFile("shared/generated/draft-catalog.json", "utf8"),
  );
  for (const [id, c] of Object.entries(champions))
    if (previous.champions[id]?.splash)
      c.splash = previous.champions[id].splash;
} catch {}
await writeFile(
  "shared/generated/draft-catalog.json",
  JSON.stringify(
    { version, source: "https://ddragon.leagueoflegends.com", champions },
    null,
    2,
  ) + "\n",
);
console.log(
  `PASS: ${entries.length} champions with local icons and base loading portraits, patch ${version}`,
);
